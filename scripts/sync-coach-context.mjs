// Copies coach-fitness-contexte.md (single source of truth, at the repo root) into a TS module
// that Edge Functions can import. Edge Functions are bundled from supabase/functions only,
// so they cannot read the root file at runtime. Run `npm run sync:coach` after editing it.
import { readFileSync, writeFileSync } from 'node:fs';

const md = readFileSync(new URL('../coach-fitness-contexte.md', import.meta.url), 'utf8');
const out = `// AUTO-GENERATED by scripts/sync-coach-context.mjs. Do not edit by hand.
export const COACH_SYSTEM_PROMPT = ${JSON.stringify(md)};
`;
writeFileSync(new URL('../supabase/functions/_shared/coach-context.ts', import.meta.url), out);
console.log('coach-context.ts updated (' + md.length + ' chars)');
